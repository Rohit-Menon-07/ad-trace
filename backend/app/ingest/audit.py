"""Deterministic writers for configs/alias_make.yaml, docs/make_audit.md and docs/duplicates_audit.md."""

from __future__ import annotations

from collections import Counter
from typing import Any

import yaml

from backend.app.ingest.duplicates import GroupResult
from backend.app.ingest.makes import AIRBUS_SAS, NEVER_MERGE, STOPWORDS, AliasEntry, candidate_merges

GENERATED = "AUTO-GENERATED by `python -m backend.app.ingest.run`. Rules live in backend/app/ingest/{}."


def _md_cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def alias_yaml(alias: dict[str, AliasEntry]) -> str:
    doc = {
        "stopwords": sorted(STOPWORDS),
        "never_merge": [{"key_prefix": p, "must_not_become": f} for p, f in NEVER_MERGE],
        "conditional": [
            {"raw": "Airbus", "if_subject_contains": AIRBUS_SAS, "then": AIRBUS_SAS, "else": "Airbus"},
        ],
        "aliases": {
            raw: {"canonical": e.canonical, "family": e.family, "key": e.key, "rule": e.rule, "rows": e.count}
            for raw, e in sorted(alias.items(), key=lambda kv: kv[0].lower())
        },
    }
    return f"# {GENERATED.format('makes.py')}\n" + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)


def make_audit_md(
    alias: dict[str, AliasEntry],
    cell_counts: Counter[str],
    airbus_rows: list[dict[str, Any]],
    missing_make_rows: list[dict[str, Any]],
) -> str:
    lines = [
        "# Make canonicalisation audit",
        "",
        f"_{GENERATED.format('makes.py')}_",
        "",
        f"- Distinct raw Make cells: **{len(cell_counts)}** (incl. multi-make cells). "
        f"Distinct individual raw names after splitting `A | B` cells: **{len(alias)}**.",
        f"- Distinct canonical makes: **{len({e.canonical for e in alias.values()} | {AIRBUS_SAS})}**.",
        f"- Normalised key: NFKC, lowercase, punctuation → space, drop {sorted(STOPWORDS)}.",
        "- Never merged: Airbus Helicopters* / Airbus Canada* → Airbus SAS; McDonnell Douglas → Boeing "
        "(enforced by a guard that raises).",
        '- make_family = "Airbus" for every canonical make starting with "Airbus"; otherwise family = canonical.',
        "",
        "## Every raw name",
        "",
        "| Raw value | Rows | Canonical | Family | Rule | Reason |",
        "|---|---:|---|---|---|---|",
    ]
    for raw, e in sorted(alias.items(), key=lambda kv: (kv[1].canonical.lower(), kv[0])):
        lines.append(
            f"| {_md_cell(raw)} | {e.count} | {_md_cell(e.canonical)} | {_md_cell(e.family)} | {e.rule} | "
            f"{_md_cell(e.reason)} |"
        )
    lines += ["", '## Plain "Airbus" rows (conditional rule)', ""]
    to_sas = [r for r in airbus_rows if r["canonical"] == AIRBUS_SAS]
    lines.append(
        f'{len(airbus_rows)} rows have Make = "Airbus"; {len(to_sas)} have "Airbus SAS" in the Subject Heading '
        f'and were merged; {len(airbus_rows) - len(to_sas)} stay "Airbus" (family Airbus).'
    )
    lines += ["", "| Record | Docket | Subject Heading | Canonical |", "|---|---|---|---|"]
    lines += [
        f"| {r['id']} | {_md_cell(r['docket'])} | {_md_cell(r['subject'])} | {r['canonical']} |" for r in airbus_rows
    ]
    lines += ["", "## Rows with no Make", "", "Left null (never inferred from the Subject Heading).", ""]
    lines += [f"- {r['id']} ({r['docket']}): {_md_cell(r['subject'])}" for r in missing_make_rows]
    lines += [
        "",
        "## Candidate merges NOT applied (for human review)",
        "",
        "Distinct canonical makes sharing a first word. They may be the same entity, a renamed one, or "
        "different companies; they were left separate because no rule covers them.",
        "",
    ]
    lines += [f"- {_md_cell(a)} ↔ {_md_cell(b)}" for a, b in candidate_merges(alias)]
    multi = [c for c in cell_counts if " | " in c]
    lines += ["", "## Multi-make cells", "", f"{len(multi)} raw cells list several makes separated by ` | `. "
              "Each part is canonicalised separately and stored in `record_makes`; `records.make_canonical` "
              "joins them with ` | `.", ""]  # fmt: skip
    lines += [f"- ({cell_counts[c]} rows) {_md_cell(c)}" for c in sorted(multi)]
    return "\n".join(lines) + "\n"


_CLASS_TEXT = {
    "exact_duplicate": "Same docket and identical make, model, subject heading and summary. The earliest issue date "
    "is kept; later copies get is_duplicate = 1 and duplicate_of, and are excluded from retrieval by default.",
    "multi_product": "Same docket, different canonical makes or different non-empty Model values. All rows kept.",
    "correction": "Docket ends in R<n> or Comments mention an OFR correction. All rows kept.",
    "revision_series": "Same docket and make, but different publications over time (proposal, supplemental or "
    "revised NPRM, withdrawal, extension). All rows kept; lineage is parsed in Prompt 4. "
    "This class is not in the original brief; see DECISIONS.md.",
}


def duplicates_md(groups: list[GroupResult], records: dict[str, dict[str, Any]]) -> str:
    counts = Counter(g.cls for g in groups)
    multi_row = [g for g in groups if len(g.record_ids) > 1]
    n_dup = sum(len(g.duplicate_of) for g in groups)
    lines = [
        "# Duplicate-docket audit",
        "",
        f"_{GENERATED.format('duplicates.py')}_",
        "",
        f"- Rows: **{len(records)}**; unique dockets: **{len(groups)}**; dockets with >1 row: **{len(multi_row)}** "
        f"covering **{sum(len(g.record_ids) for g in multi_row)}** rows.",
        f"- Rows marked is_duplicate: **{n_dup}** (kept in the DB, excluded from retrieval by default). "
        "No row is ever deleted.",
        "",
        "| Class | Docket groups | Rows |",
        "|---|---:|---:|",
    ]
    for cls in ("single", "revision_series", "multi_product", "exact_duplicate", "correction"):
        rows = sum(len(g.record_ids) for g in groups if g.cls == cls)
        lines.append(f"| {cls} | {counts.get(cls, 0)} | {rows} |")
    for cls, text in _CLASS_TEXT.items():
        examples = [g for g in groups if g.cls == cls][:5]
        lines += ["", f"## {cls} ({counts.get(cls, 0)} groups; up to 5 examples)", "", text, ""]
        for g in examples:
            lines.append(f"### {_md_cell(g.docket)}{' (' + g.note + ')' if g.note else ''}")
            lines += ["", "| Record | Issued | Make | Model | Subject | Summary starts | Duplicate of |",
                      "|---|---|---|---|---|---|---|"]  # fmt: skip
            for rid in g.record_ids:
                r = records[rid]
                lines.append(
                    f"| {rid} | {r['issue_date'] or ''} | {_md_cell(r['make_raw'])} | {_md_cell(r['model_raw'])[:60]} "
                    f"| {_md_cell(r['subject_heading'])[:90]} | {_md_cell(r['summary'])[:90]} | "
                    f"{g.duplicate_of.get(rid, '')} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"
