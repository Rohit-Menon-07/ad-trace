"""Export the API JSON Schema and regenerate frontend/src/types/api.ts from backend/app/schemas.py.

Usage: python -m backend.app.export_types

A small purpose-built JSON Schema -> TypeScript converter (covers exactly the constructs our
Pydantic models produce) keeps the check pure-Python, so pytest can fail on drift without Node.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import models_json_schema

from backend.app import schemas as s

ROOT = Path(__file__).resolve().parents[2]
TS_PATH = ROOT / "frontend" / "src" / "types" / "api.ts"
SCHEMA_PATH = ROOT / "docs" / "api.schema.json"

# Request bodies use validation mode (fields with defaults are optional in TS).
INPUT_MODELS: list[type[BaseModel]] = [s.SearchRequest, s.FeedbackRequest]
# Responses use serialization mode (every field is always present).
OUTPUT_MODELS: list[type[BaseModel]] = [
    s.SearchResponse,
    s.RecordDetail,
    s.MetaResponse,
    s.EvalResults,
    s.ExampleQuery,
    s.HealthResponse,
    s.FeedbackResponse,
]
# Literal aliases emitted as named TS types; matching inline unions are replaced by the name.
NAMED_ALIASES: dict[str, Any] = {
    "Verdict": s.Verdict,
    "SearchStatus": s.SearchStatus,
    "ReasonCode": s.ReasonCode,
    "LineageRelation": s.LineageRelation,
    "CommentPeriod": s.CommentPeriod,
    "Confidence": s.Confidence,
    "TraceStatus": s.TraceStatus,
}

HEADER = """\
// AUTO-GENERATED by `python -m backend.app.export_types` from backend/app/schemas.py.
// Do not edit by hand: change the Pydantic models and regenerate. A pytest fails on drift.

/** ISO date string, e.g. "2026-10-31". Pydantic `date` serialises to this. */
export type ISODate = string;
"""


def build_json_schema() -> dict[str, Any]:
    pairs = [(m, "validation") for m in INPUT_MODELS] + [(m, "serialization") for m in OUTPUT_MODELS]
    _, schema = models_json_schema(pairs, title="AD Trace API")  # type: ignore[arg-type]
    return schema


def _ts_literal(value: Any) -> str:
    return "'" + str(value).replace("'", "\\'") + "'" if isinstance(value, str) else json.dumps(value)


def ts_type(node: dict[str, Any], aliases: dict[str, str]) -> str:
    """Render one JSON Schema node as a TypeScript type expression."""
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in node:
        parts = [ts_type(n, aliases) for n in node["anyOf"]]
        non_null = [p for p in parts if p != "null"]
        rendered = " | ".join(non_null + (["null"] if "null" in parts else []))
        return rendered
    if "const" in node:
        return _ts_literal(node["const"])
    if "enum" in node:
        union = " | ".join(_ts_literal(v) for v in node["enum"])
        return aliases.get(union, union)
    kind = node.get("type")
    if kind == "string":
        return "ISODate" if node.get("format") == "date" else "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = ts_type(node.get("items", {}), aliases)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        extra = node.get("additionalProperties")
        value = ts_type(extra, aliases) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _jsdoc(text: str | None, indent: str) -> list[str]:
    return [f"{indent}/** {text} */"] if text else []


def ts_interface(name: str, node: dict[str, Any], aliases: dict[str, str]) -> str:
    required = set(node.get("required", []))
    lines = _jsdoc(node.get("description"), "")
    lines.append(f"export interface {name} {{")
    for prop, sub in node.get("properties", {}).items():
        lines += _jsdoc(sub.get("description"), "  ")
        opt = "" if prop in required else "?"
        lines.append(f"  {prop}{opt}: {ts_type(sub, aliases)};")
    lines.append("}")
    return "\n".join(lines)


def render_ts() -> str:
    schema = build_json_schema()
    alias_blocks: list[str] = []
    aliases: dict[str, str] = {}
    for name, typ in NAMED_ALIASES.items():
        union = ts_type(TypeAdapter(typ).json_schema(), {})
        aliases[union] = name
        alias_blocks.append(f"export type {name} = {union};")
    defs = schema.get("$defs", {})
    interfaces = [ts_interface(name, defs[name], aliases) for name in sorted(defs)]
    return HEADER + "\n" + "\n".join(alias_blocks) + "\n\n" + "\n\n".join(interfaces) + "\n"


def render_schema_json() -> str:
    return json.dumps(build_json_schema(), indent=2, sort_keys=True) + "\n"


def write(path: Path, content: str) -> bool:
    """Write with LF endings; return True if the file changed."""
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == content:
        return False
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def main() -> None:
    for path, content in ((TS_PATH, render_ts()), (SCHEMA_PATH, render_schema_json())):
        changed = write(path, content)
        print(f"{'updated' if changed else 'unchanged'}: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
