import { useState, type ReactNode } from 'react';
import { CheckCircle2, AlertTriangle, OctagonX } from 'lucide-react';
import type { TraceStep } from '../types/api';
import { CitationChip, type DrawerTarget } from './CitationChip';

interface Props {
  trace: TraceStep[];
  rationale: string[];
  numbering: Map<string, number>;
  activeId: string | null;
  onOpen: (t: DrawerTarget) => void;
}

type Tab = 'trace' | 'rationale';

const STATUS_ICON = {
  ok: { Icon: CheckCircle2, label: 'OK', cls: 'text-green-700 dark:text-green-400' },
  warn: { Icon: AlertTriangle, label: 'WARN', cls: 'text-amber-600' },
  stop: { Icon: OctagonX, label: 'STOP', cls: 'text-amber-800 dark:text-amber-400' },
} as const;

const EVIDENCE_REF = /\[([^\]\s]+#s\d+)\]/g;

export function WhyPanel({ trace, rationale, numbering, activeId, onOpen }: Props) {
  const [tab, setTab] = useState<Tab>('trace');
  return (
    <details className="rounded border border-slate-300 dark:border-slate-700">
      <summary className="cursor-pointer p-3 text-sm font-semibold">Why this answer</summary>
      <div className="border-t border-slate-300 p-3 dark:border-slate-700">
        <div role="tablist" aria-label="Explanation" className="mb-3 flex gap-1">
          <TabButton id="trace" tab={tab} setTab={setTab}>Pipeline trace</TabButton>
          <TabButton id="rationale" tab={tab} setTab={setTab}>Model rationale</TabButton>
        </div>
        {tab === 'trace' ? (
          <div role="tabpanel" id="panel-trace" aria-labelledby="tab-trace">
            <p className="mb-2 text-xs text-slate-600 dark:text-slate-400">Generated by code at each pipeline stage. This is the authoritative record of what was checked.</p>
            <ol className="space-y-1.5 text-sm">
              {trace.map((s, i) => {
                const { Icon, label, cls } = STATUS_ICON[s.status];
                return (
                  <li key={i} className="flex gap-2">
                    <Icon aria-label={label} className={`mt-0.5 h-4 w-4 shrink-0 ${cls}`} />
                    <div className="flex-1">
                      <span className="font-semibold">{s.stage}</span> <span className="text-xs font-semibold">[{label}]</span>: {s.summary}
                      {Object.keys(s.details).length > 0 && (
                        <code className="mt-0.5 block break-all text-xs text-slate-600 dark:text-slate-400">{JSON.stringify(s.details)}</code>
                      )}
                    </div>
                    <span className="shrink-0 font-mono text-xs text-slate-600 dark:text-slate-400">{s.ms} ms</span>
                  </li>
                );
              })}
            </ol>
          </div>
        ) : (
          <div role="tabpanel" id="panel-rationale" aria-labelledby="tab-rationale">
            <p className="mb-2 rounded border border-amber-500 px-2 py-1 text-xs">
              Written by the model, checked against sources. Model self-explanations can be wrong; each step must point at evidence so you can check it.
            </p>
            {rationale.length === 0 ? (
              <p className="text-sm text-slate-600 dark:text-slate-400">No model rationale: the model was not called for this request.</p>
            ) : (
              <ol className="list-decimal space-y-1 pl-5 text-sm">
                {rationale.map((step, i) => (
                  <li key={i}>{renderWithChips(step, numbering, activeId, onOpen)}</li>
                ))}
              </ol>
            )}
          </div>
        )}
      </div>
    </details>
  );
}

function TabButton({ id, tab, setTab, children }: { id: Tab; tab: Tab; setTab: (t: Tab) => void; children: string }) {
  const selected = tab === id;
  return (
    <button
      type="button"
      role="tab"
      id={`tab-${id}`}
      aria-selected={selected}
      aria-controls={`panel-${id}`}
      onClick={() => setTab(id)}
      className={`rounded border px-3 py-1 text-sm ${selected ? 'border-slate-900 bg-slate-900 text-white dark:border-slate-100 dark:bg-slate-100 dark:text-slate-900' : 'border-slate-400'}`}
    >
      {children}
    </button>
  );
}

/** Replaces "[R0001#s2]" references in model text with citation chips. */
function renderWithChips(text: string, numbering: Map<string, number>, activeId: string | null, onOpen: (t: DrawerTarget) => void) {
  const out: ReactNode[] = [];
  let last = 0;
  for (const m of text.matchAll(EVIDENCE_REF)) {
    const id = m[1] as string;
    out.push(text.slice(last, m.index));
    out.push(<CitationChip key={`${id}-${m.index}`} n={numbering.get(id) ?? id.split('#')[1] ?? id} target={{ evidenceId: id }} active={activeId === id} onOpen={onOpen} />);
    last = m.index + m[0].length;
  }
  out.push(text.slice(last));
  return out;
}
